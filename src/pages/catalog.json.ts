import type { APIContext } from "astro";
import { PROFILE, SOCIAL_LINKS } from "../config";
import { getCatalog, homepage, SHELVES } from "../lib/catalog";

/** Public project catalog. The GitHub profile README is generated from it. */
export async function GET(context: APIContext) {
  const site = context.site ?? new URL("https://itsjavi.com");
  const catalog = await getCatalog();
  const libraries = catalog.filter((p) => p.data.shelf === "libs" && !p.data.readme);

  const body = {
    $comment: "Generated by itsjavi.com. Edit src/content/projects in itsjavi/itsjavi.github.io.",
    profile: { ...PROFILE, url: site.href, links: SOCIAL_LINKS },
    projects: catalog.map((p) => ({
      id: p.id,
      name: p.data.name,
      tagline: p.data.tagline,
      readmeTagline: p.data.readmeTagline ?? p.data.tagline,
      description: p.data.description,
      shelf: p.data.shelf,
      shelfTitle: p.data.shelf ? SHELVES[p.data.shelf].title : undefined,
      kind: p.data.kind,
      url: new URL(`/projects/${p.id}/`, site).href,
      homepage: new URL(homepage(p), site).href,
      repo: p.data.repo ? `https://github.com/${p.data.repo}` : undefined,
      npm: p.data.npm ? `https://www.npmjs.com/package/${p.data.npm}` : undefined,
      icon: p.data.icon ? new URL(`/icons/${p.id}.png`, site).href : undefined,
      readme: p.data.readme,
      release: p.release && {
        version: p.release.version,
        date: p.release.date.toISOString(),
        url: p.release.url,
      },
    })),
    // Shown as one "Libraries" tile in the README.
    libraries: {
      count: libraries.length,
      url: new URL("/projects/libraries/", site).href,
      icon: new URL("/icons/libraries.png", site).href,
    },
  };

  return new Response(JSON.stringify(body, null, 2), {
    headers: { "Content-Type": "application/json; charset=utf-8" },
  });
}
